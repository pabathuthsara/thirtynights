export type QuestionSetId = keyof typeof questionSets;

export const QUESTION_VERSION = '2026-08-v1';

export function questionAssignment(nightIndex: number) {
  const segment = Math.floor((nightIndex - 1) / 30);
  const set = (['set_a', 'set_b', 'set_c'][segment % 3] ?? 'set_a') as QuestionSetId;
  const position = ((nightIndex - 1) % 30) + 1;
  return {
    set,
    position,
    questionId: `${set}_${String(position).padStart(2, '0')}`,
    questionVersion: QUESTION_VERSION,
  };
}

export function questionFor(set: QuestionSetId, nightIndex: number) {
  const questions = questionSets[set];
  return questions[(nightIndex - 1) % questions.length] ?? questions[0];
}
